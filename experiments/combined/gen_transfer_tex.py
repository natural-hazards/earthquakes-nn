"""Generate the LaTeX tables for the transfer-to-OKC section from results_s20/ and
results_final_s20/ (longer OKC records), written to transfer_tables.tex.

Usage: python gen_transfer_tex.py [output.tex]
"""
import os, sys, glob, json, collections
import numpy as np

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
OUT = sys.argv[1] if len(sys.argv) > 1 else 'transfer_tables.tex'
SEL, FIN = 'results_s20', 'results_final_s20'
DATA = {'all': 'SPF + OKC', 'okc': 'OKC only', 'orig': 'SPF only'}


def load(d):
    g = collections.defaultdict(list)
    for fn in glob.glob(f'{d}/*.json'):
        r = json.load(open(fn))
        g[r['name'].rsplit('_s', 1)[0]].append(r)
    return g


sel, fin = load(SEL), load(FIN)


def ms(v, digits=3):
    v = np.asarray(v, float)
    return f'{v.mean():.{digits}f} $\\pm$ {v.std():.{digits}f}'


def test(rs, src, key='macro_f1'):
    return [r['test'][src][key] for r in rs]


def f1(rs, src):
    return np.mean([r['test'][src]['f1'] for r in rs], 0)


def cm(rs, src):
    return np.rint(np.mean([r['test'][src]['cm'] for r in rs], 0)).astype(int)


L = []
w = L.append
w('% Auto-generated by experiments/combined/gen_transfer_tex.py -- do not edit by hand.')
w('')

# ------------------------------------------------------------- Table: strategies (final models)
w(r'\begin{table}[tb]')
w(r'  \centering')
w(r'  \caption{Ternary classification on the OKC test events (699~E, 5,379~M, 46~T) with '
  r'EfficientNet-B0 trained in four ways; mean $\pm$ std over three seeds. '
  r"``SPF test'' is the same model evaluated on the SPF part of the test split "
  r'(450~E, 10,942~M, 559~T). The record length $D$ is the one selected on the '
  r'validation split for each strategy; fine-tuning starts from the SPF-only model and '
  r'continues on the OKC training events for 15 epochs at a learning rate of $10^{-4}$.}')
w(r'  \label{tab:transfer-strategies}')
w(r'  \begin{tabular}{llcccccc}')
w(r'    \toprule')
w(r'    Training data & $D$ [s] & \multicolumn{4}{c}{OKC test} & SPF test \\')
w(r'    \cmidrule(lr){3-6} \cmidrule(lr){7-7}')
w(r'    & & Macro-F1 & F1$_\mathrm{E}$ & F1$_\mathrm{M}$ & F1$_\mathrm{T}$ & Macro-F1 \\')
w(r'    \midrule')
rows = [
    ('OKC only', 'effnet_EMT_okc_D16_log1_lr0.001_g0.85_e30'),
    ('SPF + OKC (pooled)', 'effnet_EMT_all_D20_log1_lr0.001_g0.85_e30'),
    ('SPF, fine-tuned on OKC', 'effnet_EMT_okc_D20_log1_lr0.0001_g0.85_e15_ft'),
    ('SPF only (no OKC data)', 'effnet_EMT_orig_D20_log1_lr0.001_g0.85_e30'),
]
for label, cfg in rows:
    rs = fin[cfg]
    D = rs[0]['args']['duration']
    f = f1(rs, 'okc')
    w(f"    {label} & {D} & {ms(test(rs, 'okc'))} & {f[0]:.3f} & {f[1]:.3f} & {f[2]:.3f} & {ms(test(rs, 'orig'))} \\\\")
w(r'    \bottomrule')
w(r'  \end{tabular}')
w(r'\end{table}')
w('')

# ------------------------------------------------------------- Table: record length x training data (selection)
w(r'\begin{table}[tb]')
w(r'  \centering')
w(r'  \caption{Model selection for the OKC station: macro-F1 of EfficientNet-B0 on the OKC part '
  r'of the validation split as a function of the record length $D$ and of the '
  r'training data (selection runs, trained on the training split only; mean $\pm$ std over '
  r'three seeds). The last column gives the number of the 21 OKC tectonic validation events '
  r'that are recognised (rounded mean over the seeds).}')
w(r'  \label{tab:transfer-length}')
w(r'  \begin{tabular}{llccc}')
w(r'    \toprule')
w(r'    Training data & $D$ [s] & Macro-F1 (OKC) & F1$_\mathrm{T}$ (OKC) & T recognised \\')
w(r'    \midrule')
for data in ('okc', 'all'):  # the SPF-only runs have no OKC events in their validation split
    for D in (8, 16, 20):
        cfg = f'effnet_EMT_{data}_D{D}_log1_lr0.001_g0.85_e30'
        rs = sel[cfg]
        c = np.rint(np.mean([r['val']['okc']['cm'] for r in rs], 0)).astype(int)
        vf1 = [r['val']['okc']['macro_f1'] for r in rs]
        vf1t = np.mean([r['val']['okc']['f1'][2] for r in rs])
        n_t = int(round(np.mean([sum(r['val']['okc']['cm'][2]) for r in rs])))
        w(f"    {DATA[data]} & {D} & {ms(vf1)} & {vf1t:.3f} & {c[2, 2]} / {n_t} \\\\")
    if data != 'all':
        w(r'    \midrule')
w(r'    \bottomrule')
w(r'  \end{tabular}')
w(r'\end{table}')
w('')

# ------------------------------------------------------------- Table: confusion matrices, OKC part
w(r'\begin{table}[tb]')
w(r'  \centering')
w(r'  \caption{Confusion matrices on the OKC test events (rows: true class, columns: predicted; '
  r'averaged over three seeds and rounded) for the pooled model and for the SPF-only model '
  r'applied to OKC without any OKC training data.}')
w(r'  \label{tab:transfer-confusion}')
w(r'  \begin{tabular}{llrrr}')
w(r'    \toprule')
w(r'    Model & True & \multicolumn{1}{c}{$\hat{\mathrm{E}}$} & \multicolumn{1}{c}{$\hat{\mathrm{M}}$} & \multicolumn{1}{c}{$\hat{\mathrm{T}}$} \\')
w(r'    \midrule')
for i, (label, cfg) in enumerate([('SPF + OKC (pooled)', rows[1][1]), ('SPF only', rows[3][1])]):
    if i:
        w(r'    \midrule')
    c = cm(fin[cfg], 'okc')
    for k, cl in enumerate('EMT'):
        head = rf'\multirow{{3}}{{*}}{{{label}}}' if k == 0 else ''
        cells = ' & '.join(rf'\textbf{{{c[k, j]}}}' if k == j else str(c[k, j]) for j in range(3))
        w(f'    {head} & {cl} & {cells} \\\\')
w(r'    \bottomrule')
w(r'  \end{tabular}')
w(r'\end{table}')

open(OUT, 'w').write('\n'.join(L) + '\n')
print('written', OUT)

# numbers for the prose
print('\nprose numbers:')
for label, cfg in rows:
    rs = fin[cfg]
    c = cm(rs, 'okc')
    print(f'  {label:28s} OKC {ms(test(rs, "okc"))}  SPF {ms(test(rs, "orig"))}  all {ms(test(rs, "all"))}  '
          f'cm okc {c.tolist()}  E->M {c[0,1]} M->E {c[1,0]} M->T {c[1,2]} T->M {c[2,1]}')
for task in ('E_M', 'T_M'):
    cfg = f'effnet_{task}_all_D20_log1_lr0.001_g0.85_e30'
    rs = fin[cfg]
    print(f'  binary {task}: all {ms(test(rs, "all"))} okc {ms(test(rs, "okc"))} auc okc {ms([r["test"]["okc"]["roc_auc"] for r in rs])} spf {ms(test(rs, "orig"))}')
