def val(cfg):
    rs = sel.get(cfg)
    return ms([r['val']['macro_f1'] for r in rs]) if rs else '--'


def val_f1(cfg):
    rs = sel.get(cfg)
    if not rs:
        return '--', '--', '--'
    f = np.array([r['val']['f1'] for r in rs]).mean(0)
    return tuple(f'{x:.3f}' for x in f)


