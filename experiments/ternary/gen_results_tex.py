# the --duration argument counts 100-sample units; the data are sampled at 125 Hz
SEC = {10: 8, 20: 16, 30: 24}


def load(pattern):
    groups = collections.defaultdict(list)
    for fn in glob.glob(pattern):
        r = json.load(open(fn))
        groups[r['name'].rsplit('_s', 1)[0]].append(r)
    return groups


def ms(values, digits=3):
    v = np.asarray(values, float)
    return f'{v.mean():.{digits}f} $\\pm$ {v.std():.{digits}f}'


def cm_stats(cm):
    cm = np.asarray(cm, float)
    tp = np.diag(cm)
    prec = tp / cm.sum(0)
    rec = tp / cm.sum(1)
    acc = tp.sum() / cm.sum()
    return prec, rec, acc


